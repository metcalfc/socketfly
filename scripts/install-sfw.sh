#!/usr/bin/env bash
# Runs INSIDE the Sprite: sprite exec -s <name> -- bash -s < scripts/install-sfw.sh
# Installs the Socket Firewall Free binary to ~/.local/bin and adds
# package-manager shims that route through it.
set -euo pipefail

SFW_VERSION="${SFW_VERSION:-v1.16.0}"
BIN="$HOME/.local/bin"
mkdir -p "$BIN"

case "$(uname -m)" in
  x86_64)  asset=sfw-free-linux-x86_64 ;;
  aarch64) asset=sfw-free-linux-arm64 ;;
  *) echo "unsupported arch: $(uname -m)" >&2; exit 1 ;;
esac

# Release binary, not `npm i -g sfw`: on a Sprite the npm global bin dir lives
# under the nvm tree and is not on PATH.
curl -fsSL -o "$BIN/sfw" \
  "https://github.com/SocketDev/sfw-free/releases/download/$SFW_VERSION/$asset"
chmod +x "$BIN/sfw"

# Shims: ~/.local/bin is ahead of /.sprite/bin on the Sprite PATH, so these win
# for anything that resolves the tool by name. If we are already inside sfw
# (its CA bundle is in SSL_CERT_FILE), call the real tool directly.
for tool in npm npx pnpm yarn pip pip3 uv cargo; do
  real="/.sprite/bin/$tool"
  [ -x "$real" ] || continue
  cat > "$BIN/$tool" <<EOF
#!/bin/bash
# sfw shim, generated by install-sfw.sh
case "\${SSL_CERT_FILE:-}" in */sfw-*/socketFirewall*) exec "$real" "\$@" ;; esac
exec "$BIN/sfw" "$real" "\$@"
EOF
  chmod +x "$BIN/$tool"
  echo "shim: $tool -> sfw $real"
done

"$BIN/sfw" --help | head -1
echo "installed: $BIN/sfw ($SFW_VERSION)"
